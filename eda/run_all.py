"""Run every EDA step in order and write an index of the generated reports."""
from __future__ import annotations

import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from common import REPORT_DIR, ROOT  # noqa: E402


def main() -> None:
    steps = sorted(HERE.glob("[0-9][0-9]_*.py"))
    for step in steps:
        t0 = time.time()
        print(f"── {step.name}")
        subprocess.run([sys.executable, str(step)], check=True, cwd=ROOT)
        print(f"   done in {time.time() - t0:.1f}s")
    lines = ["# EDA reports", "", "Generated by `python eda/run_all.py`.", ""]
    for md in sorted(REPORT_DIR.glob("[0-9][0-9]_*.md")):
        title = md.read_text().splitlines()[0].lstrip("# ").strip()
        lines.append(f"- [{title}]({md.name})")
    (REPORT_DIR / "README.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {(REPORT_DIR / 'README.md').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
